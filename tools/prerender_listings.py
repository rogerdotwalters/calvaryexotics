#!/usr/bin/env python3
"""Pre-render crested gecko listings into crested-geckos.html for SEO.

js/listing.js fills the page from data/listings.json in the browser, which
means crawlers that do not run JavaScript see an empty list. This script
writes the same data into the HTML as plain markup plus schema.org Product
JSON-LD. The browser swaps the static markup for the trading cards on load.

Re-run after editing data/listings.json:

    python3 tools/prerender_listings.py
"""
import json
import re
from datetime import date
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "crested-geckos.html"
DATA = ROOT / "data" / "listings.json"
SITE = "https://www.calvaryexotics.com"
ANIMAL_TYPE = "crested_gecko"

HTML_START = "<!-- PRERENDER:LISTINGS:START (generated by tools/prerender_listings.py) -->"
HTML_END = "<!-- PRERENDER:LISTINGS:END -->"
LD_START = "<!-- PRERENDER:PRODUCTS:START (generated by tools/prerender_listings.py) -->"
LD_END = "<!-- PRERENDER:PRODUCTS:END -->"


def load_geckos():
    rows = json.loads(DATA.read_text())["listings"]
    geckos = [r for r in rows if r.get("animal_type") == ANIMAL_TYPE]
    # Available first, then on hold, then sold; stable within each group.
    return sorted(geckos, key=lambda g: (bool(g.get("sold")), bool(g.get("hold"))))


def status(g):
    if g.get("sold"):
        return "Sold"
    if g.get("hold"):
        return "On hold"
    return "Available"


def hatched(g):
    try:
        return date.fromisoformat(g["hatch_date"]).strftime("%B %Y")
    except (KeyError, ValueError):
        return None


def description(g):
    parts = [f"Captive-bred {g['name']} crested gecko (Correlophus ciliatus) for sale in Tyler, TX."]
    if hatched(g):
        parts.append(f"Hatched {hatched(g)}.")
    if g.get("weight"):
        parts.append(f"Currently {g['weight']} g.")
    if g.get("sire") and g.get("dam"):
        parts.append(f"Sire: {g['sire']}. Dam: {g['dam']}.")
    return " ".join(parts)


def image_url(g):
    return f"{SITE}/{g['cover_url'].lstrip('./')}" if g.get("cover_url") else None


def anchor(g):
    return f"listing-{g['id']}"


def card_html(g):
    img = ""
    if g.get("cover_url"):
        alt = f"{g['name']} crested gecko for sale in Tyler, TX"
        img = (f'<img src="{escape(g["cover_url"])}" alt="{escape(alt)}" '
               'width="320" height="320" loading="lazy" decoding="async">')
    price = f'<p class="prerender-price">${g["price"]}</p>' if g.get("price") not in (None, "") else ""
    facts = []
    if hatched(g):
        facts.append(f"Hatched {hatched(g)}")
    if g.get("weight"):
        facts.append(f"{g['weight']} g")
    if g.get("sire") and g.get("dam"):
        facts.append(f"Sire {escape(g['sire'])} x Dam {escape(g['dam'])}")
    facts_html = f'<p>{" &middot; ".join(facts)}</p>' if facts else ""
    return (
        f'<article class="prerender-card" id="{anchor(g)}">\n'
        f'  {img}\n'
        f'  <h3>{escape(g["name"])} Crested Gecko</h3>\n'
        f'  <p class="prerender-status">{status(g)}</p>\n'
        f'  {price}\n'
        f'  {facts_html}\n'
        f'</article>'
    )


def product_ld(g):
    availability = "https://schema.org/InStock"
    if g.get("hold"):
        availability = "https://schema.org/LimitedAvailability"
    product = {
        "@type": "Product",
        "@id": f"{SITE}/crested-geckos.html#{anchor(g)}",
        "name": f"{g['name']} Crested Gecko",
        "description": description(g),
        "category": "Live reptile",
        "brand": {"@type": "Brand", "name": "Calvary Exotics"},
        "offers": {
            "@type": "Offer",
            "url": f"{SITE}/crested-geckos.html#{anchor(g)}",
            "price": f"{float(g['price']):.2f}",
            "priceCurrency": "USD",
            "availability": availability,
            "itemCondition": "https://schema.org/NewCondition",
            "seller": {"@type": "Organization", "name": "Calvary Exotics", "url": f"{SITE}/"},
        },
    }
    if g.get("animal_id"):
        product["sku"] = str(g["animal_id"])
    if image_url(g):
        product["image"] = image_url(g)
    return product


def replace_region(text, start, end, body):
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    if not pattern.search(text):
        raise SystemExit(f"Marker not found in {PAGE.name}: {start}")
    return pattern.sub(lambda _: f"{start}\n{body}\n{end}", text)


def main():
    geckos = load_geckos()
    page = PAGE.read_text()

    cards = "\n".join(card_html(g) for g in geckos)
    html_block = f'<div class="prerendered-listings" data-prerendered>\n{cards}\n</div>'
    page = replace_region(page, HTML_START, HTML_END, html_block)

    # Sold animals are not offers; leave them out of the structured data.
    products = [product_ld(g) for g in geckos if not g.get("sold")]
    graph_item = {"@type": "ItemList", "name": "Crested geckos for sale",
                  "itemListElement": [{"@type": "ListItem", "position": i, "item": p}
                                      for i, p in enumerate(products, 1)]}
    ld = json.dumps({"@context": "https://schema.org", "@graph": [graph_item]}, indent=2)
    ld_block = f'<script type="application/ld+json">\n{ld}\n</script>'
    page = replace_region(page, LD_START, LD_END, ld_block)

    PAGE.write_text(page)
    print(f"Rendered {len(geckos)} listings ({len(products)} in structured data) into {PAGE.name}")


if __name__ == "__main__":
    main()
